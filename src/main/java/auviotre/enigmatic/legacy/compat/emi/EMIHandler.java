package auviotre.enigmatic.legacy.compat.emi;

import auviotre.enigmatic.legacy.EnigmaticLegacy;
import auviotre.enigmatic.legacy.client.ClientRecipes;
import auviotre.enigmatic.legacy.compat.emi.recipe.SpellstoneCraftingEmiRecipe;
import auviotre.enigmatic.legacy.compat.emi.recipe.TaintingEmiRecipe;
import auviotre.enigmatic.legacy.contents.crafting.AnnihilatingRecipe;
import auviotre.enigmatic.legacy.contents.crafting.SpellstoneTableRecipe;
import auviotre.enigmatic.legacy.registries.*;
import dev.emi.emi.api.EmiEntrypoint;
import dev.emi.emi.api.EmiPlugin;
import dev.emi.emi.api.EmiRegistry;
import dev.emi.emi.api.recipe.EmiCraftingRecipe;
import dev.emi.emi.api.recipe.EmiRecipeCategory;
import dev.emi.emi.api.stack.EmiIngredient;
import dev.emi.emi.api.stack.EmiStack;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.item.crafting.Ingredient;
import net.minecraft.world.item.crafting.RecipeHolder;

import java.util.List;

/**
 * 26.1.2 port: native EMI (SEMI) plugin mirroring JEIHandler. Brewing and anvil repair recipes are generated by EMI itself.
 */
@EmiEntrypoint
public class EMIHandler implements EmiPlugin {
    public static final EmiRecipeCategory SPELLSTONE_CRAFTING = new EmiRecipeCategory(EnigmaticLegacy.location("spellstone_crafting"), EmiStack.of(EnigmaticItems.SPELLCORE));
    public static final EmiRecipeCategory TAINTING = new EmiRecipeCategory(EnigmaticLegacy.location("tainting"), EmiStack.of(EnigmaticItems.EARTH_HEART));

    public void register(EmiRegistry registry) {
        registry.addCategory(SPELLSTONE_CRAFTING);
        registry.addCategory(TAINTING);
        registry.addWorkstation(SPELLSTONE_CRAFTING, EmiStack.of(EnigmaticBlocks.SPELLSTONE_TABLE));
        registry.addRecipeHandler(EnigmaticMenus.SPELLSTONE_TABLE_MENU.get(), new SpellstoneTableRecipeHandler());

        // The server syncs this recipe type itself (EnigmaticEventHandler#onDatapackSync), with or without SEMI on the server.
        for (RecipeHolder<SpellstoneTableRecipe> holder : ClientRecipes.byType(EnigmaticRecipes.SPELLSTONE_CRAFTING.get())) {
            registry.addRecipe(new SpellstoneCraftingEmiRecipe(holder.id().identifier(), holder.value(), false));
        }
        SpellstoneTableRecipe fragmentation = new SpellstoneTableRecipe(EnigmaticItems.SPELLSTONE_DEBRIS.toStack(4), 0, List.of(), false);
        registry.addRecipe(new SpellstoneCraftingEmiRecipe(EnigmaticLegacy.location("/spellstone_fragmentation"), fragmentation, true));

        Ingredient cursedRing = Ingredient.of(EnigmaticItems.CURSED_RING);
        Ingredient twoRing = Ingredient.of(EnigmaticItems.CURSED_RING, EnigmaticItems.REDEMPTION_RING);
        registry.addRecipe(new TaintingEmiRecipe(EnigmaticItems.EARTH_HEART.toStack(), twoRing));
        registry.addRecipe(new TaintingEmiRecipe(EnigmaticItems.TWISTED_HEART.toStack(), cursedRing));
        registry.addRecipe(new TaintingEmiRecipe(EnigmaticItems.PURE_HEART.toStack(), twoRing));
        registry.addRecipe(new TaintingEmiRecipe(EnigmaticItems.ABYSSAL_HEART.toStack(), cursedRing));

        // AnnihilatingRecipe is a CustomRecipe, which EMI does not display on its own.
        EmiIngredient abyssal = EmiIngredient.of(EnigmaticTags.Items.ABYSSAL_ITEMS);
        List<EmiIngredient> inputs = List.of(
                abyssal, EmiStack.of(EnigmaticItems.EVIL_INGOT), abyssal,
                EmiStack.EMPTY, EmiStack.of(tainted(EnigmaticItems.ABYSSAL_HEART.toStack())), EmiStack.EMPTY,
                abyssal, EmiStack.of(tainted(EnigmaticItems.TWISTED_HEART.toStack())), abyssal
        );
        registry.addRecipe(new EmiCraftingRecipe(inputs, EmiStack.of(AnnihilatingRecipe.INSTANCE.getResultItem()), EnigmaticLegacy.location("annihilating_sword"), false));
    }

    private static ItemStack tainted(ItemStack stack) {
        stack.set(EnigmaticComponents.TAINTABLE, true);
        return stack;
    }
}
